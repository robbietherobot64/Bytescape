//! ActivityPub Module — A1.1 AP Actor & Inbox/Outbox, A2.7 AP Group Actor, P4 Lemmy Compat
//!
//! Root module for Bytescape's ActivityPub federation implementation.
//! ActivityPub is the W3C protocol that enables Bytescape to communicate with
//! Mastodon, Lemmy, Pixelfed, PeerTube, and any other server speaking the same
//! protocol — turning Bytescape from a local vault into a federated participant.
//!
//! # How It Works
//!
//! 1. **Actor identity** — [`actor`] creates Ed25519-key-signed profiles that
//!    remote servers use to verify messages and display user info.
//! 2. **Outbound delivery** — [`activities`] builds ActivityPub JSON-LD messages
//!    (Create, Follow, Like, Announce, etc.). [`outbox`] delivers them to remote
//!    inboxes with HTTP Signatures generated by [`signatures`].
//! 3. **Inbound processing** — [`inbox`] receives incoming activities, verifies
//!    their HTTP Signatures against the sender's public key, and dispatches to
//!    the appropriate handler (follow-accept, note-create, etc.).
//! 4. **Discovery** — [`webfinger`] resolves `@user@domain` addresses to actor
//!    URLs, enabling search and mention lookup across the Fediverse.
//! 5. **Group federation** — [`group_actor`] federates local Bytescape groups as
//!    ActivityPub `Group` actors so remote users can join/follow them.
//! 6. **Lemmy compatibility** — [`lemmy`] handles Lemmy's non-standard
//!    `Page`-based post format and community semantics.
//!
//! # Related Files
//!
//! - `lib.rs` — registers ActivityPub Tauri commands in the invoke handler.
//! - `protocol.rs` — P2P sync (Iroh-based) complements AP federation for
//!   node-to-node replication within the Bytescape network.
//! - `connectors/mastodon.rs` — Mastodon *API* client (REST, not AP); separate
//!   from this federation layer which speaks raw ActivityPub over HTTP.

